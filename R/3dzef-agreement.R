# Wave 12A: checked handoff of Python ZF3D agreement evidence to native R.
# SHA-256 consistency does not independently authenticate the model or labels.

#' Import a SHA-256-verified 3D-ZeF published-label agreement report
#'
#' Read the Python Wave 12A output without interpreting agreement with
#' original annotated 3D head positions as surveyed physical underwater XYZ.
#' Validates all output-file hashes, row counts, per-frame and per-match
#' accounting, and agreement that the reported distances match the output
#' coordinates in source centimetres. It never infers missing time stamps,
#' class labels, independent review or automatic fish welfare information.
#'
#' @param directory Existing folder containing summary.json, per_frame.csv
#'   and matches.csv generated by aqt_3dzef_agreement.py.
#' @return An aqt_3dzef_label_agreement list with summary, per_frame,
#'   matches, and software_integrity_verified=TRUE. This does not certify
#'   that a model ran on original video or validate physical XYZ accuracy.
#' @export
aqt_3dzef_agreement_import <- function(directory) {
  if (!is.character(directory) || length(directory)!=1L ||
      is.na(directory) || !dir.exists(directory))
    stop("directory must be an existing agreement output folder",
         call.=FALSE)
  paths <- stats::setNames(
    file.path(directory,c("summary.json","per_frame.csv","matches.csv")),
    c("summary","per_frame","matches"))
  if (any(!file.exists(paths) | dir.exists(paths)))
    stop("Missing 3D-ZeF agreement file",call.=FALSE)
  meta <- tryCatch(jsonlite::fromJSON(
      paste(readLines(paths[["summary"]],warn=FALSE,encoding="UTF-8"),
            collapse="\n"), simplifyVector=FALSE),
      error=function(e) stop("Invalid 3D-ZeF agreement JSON",call.=FALSE))
  if (!is.list(meta) ||
      !identical(meta$metric_scope,
                 "agreement_with_published_3dzef_3d_head_labels") ||
      !identical(meta$source_xyz_unit,"cm") ||
      !identical(meta$independent_physical_xyz_ground_truth_verified,FALSE) ||
      !identical(meta$scientific_accuracy_certified,FALSE) ||
      !identical(meta$official_TrackEval_HOTA_computed,FALSE) ||
      !identical(meta$official_ZF3D_MOTA_computed,FALSE) ||
      !is.list(meta$artifact_sha256))
    stop("Incomplete or overclaimed 3D-ZeF benchmark metadata",call.=FALSE)
  for (nm in c("per_frame","matches")) {
    hash <- meta$artifact_sha256[[paste0(nm,".csv")]]
    if (!is.character(hash) || length(hash)!=1L ||
        !grepl("^[a-f0-9]{64}$",hash) ||
        !identical(unname(digest::digest(paths[[nm]],algo="sha256",
                                        file=TRUE)),hash))
      stop("3D-ZeF agreement SHA-256 mismatch",call.=FALSE)
  }
  frames <- utils::read.csv(paths[["per_frame"]],
                            stringsAsFactors=FALSE,check.names=FALSE)
  matches <- utils::read.csv(paths[["matches"]],
                             stringsAsFactors=FALSE,check.names=FALSE)
  fcols <- c("frame","truth_count","prediction_count","matched_count",
             "false_positives","false_negatives")
  mcols <- c("frame","truth_id","predicted_id",
             "true_x_cm","true_y_cm","true_z_cm",
             "pred_x_cm","pred_y_cm","pred_z_cm","euclidean_error_cm")
  if (!identical(names(frames),fcols) || !identical(names(matches),mcols))
    stop("Unexpected 3D-ZeF agreement column schema",call.=FALSE)
  check_nonnegative_integer <- function(x,label,positive=FALSE) {
    if (!is.numeric(x) || any(!is.finite(x)) ||
        any(x < as.integer(positive)) || any(x!=floor(x)))
      stop("Invalid 3D-ZeF field: ",label,call.=FALSE)
  }
  n <- meta$n_evaluated_frames
  full <- meta$n_full_video_frames_declared
  for (nm in c("n_evaluated_frames","n_full_video_frames_declared",
               "n_truth_inside_evaluation","n_predictions_inside_evaluation",
               "n_matches","false_positives","false_negatives")) {
    x <- meta[[nm]]
    if (!is.numeric(x) || length(x)!=1L || is.na(x) ||
        !is.finite(x) || x<0 || x!=floor(x))
      stop("Invalid 3D-ZeF summary count: ",nm,call.=FALSE)
  }
  if (full<1 || n<1 || n>full ||
      nrow(frames)!=n || nrow(matches)!=meta$n_matches)
    stop("3D-ZeF agreement frame or match counts mismatch",call.=FALSE)
  check_nonnegative_integer(frames$frame,"frame",TRUE)
  if (anyDuplicated(frames$frame) || any(frames$frame>full))
    stop("Duplicate or out-of-range evaluation frame",call.=FALSE)
  for (nm in fcols[-1L]) check_nonnegative_integer(frames[[nm]],nm)
  if (any(frames$matched_count > pmin(frames$truth_count,
                                      frames$prediction_count)) ||
      any(frames$false_positives !=
          frames$prediction_count-frames$matched_count) ||
      any(frames$false_negatives !=
          frames$truth_count-frames$matched_count) ||
      sum(frames$truth_count)!=meta$n_truth_inside_evaluation ||
      sum(frames$prediction_count)!=meta$n_predictions_inside_evaluation ||
      sum(frames$matched_count)!=meta$n_matches ||
      sum(frames$false_positives)!=meta$false_positives ||
      sum(frames$false_negatives)!=meta$false_negatives)
    stop("Inconsistent ZF3D frame accounting",call.=FALSE)
  if (nrow(matches)) {
    for (nm in c("frame","truth_id","predicted_id"))
      check_nonnegative_integer(matches[[nm]],nm,TRUE)
    for (nm in mcols[-(1:3)])
      if (!is.numeric(matches[[nm]]) || any(!is.finite(matches[[nm]])))
        stop("Invalid 3D-ZeF matched coordinates or error",call.=FALSE)
    if (any(!matches$frame %in% frames$frame) ||
        anyDuplicated(paste(matches$frame,matches$truth_id,sep="\r")) ||
        anyDuplicated(paste(matches$frame,matches$predicted_id,sep="\r")))
      stop("Repeated or out-of-scope 3D-ZeF matched identity",call.=FALSE)
    expected <- sqrt(
      (matches$pred_x_cm-matches$true_x_cm)^2 +
      (matches$pred_y_cm-matches$true_y_cm)^2 +
      (matches$pred_z_cm-matches$true_z_cm)^2)
    if (any(abs(matches$euclidean_error_cm-expected)>1e-8) ||
        any(matches$euclidean_error_cm >
            meta$association_distance_cutoff_cm+1e-8))
      stop("3D-ZeF matched distance exceeds reported geometry/cutoff",
           call.=FALSE)
    indexed <- tabulate(match(matches$frame,frames$frame),
                        nbins=nrow(frames))
    if (any(indexed!=frames$matched_count))
      stop("3D-ZeF per-frame match rows disagree with frame summary",
           call.=FALSE)
  } else if (any(frames$matched_count!=0))
    stop("Match table is empty but reported frame matches are not",
         call.=FALSE)
  structure(list(summary=meta,per_frame=frames,matches=matches,
                 software_integrity_verified=TRUE,
                 original_video_model_accuracy_verified=FALSE,
                 physical_underwater_xyz_accuracy_certified=FALSE),
            class="aqt_3dzef_label_agreement")
}
