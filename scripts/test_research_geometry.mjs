import assert from "node:assert/strict";
import {interfacePoint,apparentAirRay,refractedRay,closestRayPair,reconstructScenario,project3D,makeSyntheticMultiview,distance} from "../pkgdown/assets/research-geometry-core.mjs";
const p=interfacePoint([0,0,20],[0,0,-30],1.333);
assert.deepEqual(p,[0,0,0]);
const a=apparentAirRay([-25,0,20],[6,4,-30],1.333);
const b=apparentAirRay([25,0,20],[6,4,-30],1.333);
const rayA=refractedRay([-25,0,20],a.direction,1.333);
const rayB=refractedRay([25,0,20],b.direction,1.333);
const ca=closestRayPair(rayA,rayB);
assert.ok(ca.valid);
assert.ok(distance(ca.midpoint,[6,4,-30])<1e-6);
assert.ok(ca.rayGap<1e-6);
const ref=reconstructScenario({baseline:60,depth:30,fishX:6,fishY:4,noisePx:0});
assert.ok(ref.result.valid&&ref.reconstructedError<1e-6);
const noisy=reconstructScenario({noisePx:4,fishX:8,fishY:2});
assert.ok(Number.isFinite(noisy.result.rayGap));
assert.ok(Number.isFinite(noisy.reconstructedError));
const projected=project3D([0,0,0]);
assert.ok(Number.isFinite(projected.x)&&Number.isFinite(projected.y));
assert.equal(closestRayPair({origin:[0,0,0],direction:[0,0,-1]},{origin:[2,0,0],direction:[0,0,-1]}).valid,false);
assert.throws(()=>interfacePoint([0,0,-20],[1,0,-10]));
const scene=makeSyntheticMultiview({frames:20,fish:3});
assert.equal(scene.frames.length,40);
assert.equal(scene.tracks3d.length,60);
assert.ok(scene.frames.some(f=>f.camera_id==="CAM2"&&f.raw_time_s>f.time_s));
assert.equal(makeSyntheticMultiview({frames:20,fish:3}).tracks2d.length,scene.tracks2d.length);
console.log("AQT_RESEARCH_GEOMETRY_PASS: Snell single-interface rays, triangulation, invalid geometry and synthetic multiview clocks");
